QUIZ_TOPICS = {
    "1": ("全部題目", BASIC_QUIZ + ROLE_QUIZ + SHERIFF_QUIZ + TIGER_QUIZ),
    "2": ("基本規則", BASIC_QUIZ),
    "3": ("狼王、覺醒狼王、攝夢人、奇蹟商人", ROLE_QUIZ),
    "4": ("警長競選與自爆", SHERIFF_QUIZ),
    "5": ("村姑與虎姑婆（15 人）", TIGER_QUIZ),
}
QUIZ = QUIZ_TOPICS["1"][1]


def run_quiz(count: int = 10, rng: random.Random | None = None) -> None:
    from .human import ask

    rng = rng or random.Random()
    print("\n要練習哪一類？")
    for key, (name, qs) in QUIZ_TOPICS.items():
        print(f"  {key}. {name}（{len(qs)} 題）")
    pool = QUIZ_TOPICS.get(ask("> "), QUIZ_TOPICS["1"])[1]
    questions = rng.sample(pool, min(count, len(pool)))
    score = 0
    for i, (q, options, answer, explain) in enumerate(questions, 1):
        print(f"\n第 {i}/{len(questions)} 題：{q}")
        for j, opt in enumerate(options, 1):
            print(f"  {j}. {opt}")
        raw = ask("你的答案 > ")
        correct = raw.isdigit() and int(raw) - 1 == answer
        score += correct
        print(("✅ 答對！" if correct else f"❌ 答錯，正確答案是 {answer + 1}. {options[answer]}"))
        print(f"   💡 {explain}")
    print(f"\n🎯 得分：{score}/{len(questions)}")
