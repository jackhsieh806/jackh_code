def run_quiz(count: int = 10, rng: random.Random | None = None) -> None:
    from .human import ask

    rng = rng or random.Random()
    questions = rng.sample(QUIZ, min(count, len(QUIZ)))
    score = 0
    for i, (q, options, answer, explain) in enumerate(questions, 1):
        print(f"\n第 {i}/{len(questions)} 題：{q}")
        for j, opt in enumerate(options, 1):
            print(f"  {j}. {opt}")
        raw = ask("你的答案 > ")
        correct = raw.isdigit() and int(raw) - 1 == answer
        score += correct
        print(("✅ 答對！" if correct else f"❌ 答錯，正確答案是 {answer + 1}. {options[answer]}"))
        print(f"   💡 {explain}")
    print(f"\n🎯 得分：{score}/{len(questions)}")
